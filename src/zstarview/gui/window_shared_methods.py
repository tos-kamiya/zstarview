"""Method contract shared by the SkyWindow mixins.

The SkyWindow mixins call methods that another mixin or
``SkyWindowCoreMixin`` defines. This class declares those signatures so each
mixin can be type-checked on its own.

The stubs exist only for the type checker (``TYPE_CHECKING``). They must not
exist at runtime: ``SkyWindowClientWidget`` composes the render mixins and
forwards missing attributes to the owner window through ``__getattr__``, and a
runtime stub would shadow that forwarding.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from pathlib import Path

    import astropy.time

    from ..types import ViewerData


class SkyWindowSharedMethods:
    """Type-only method declarations for the SkyWindow mixins."""

    if TYPE_CHECKING:
        # Defined in window_update_cloud.py.
        def _geo_satellite_mode_active(self) -> bool: ...
        def request_cloud_projection_update(self, *, reason: str) -> None: ...
        def _safe_request_cloud_repaint(self) -> None: ...

        # Defined in window.py.
        def _predicted_cloud_satellite(self) -> str: ...
        def _aircraft_layer_enabled(self) -> bool: ...
        def _current_time_obj(self) -> astropy.time.Time: ...
        def _queue_periodic_debug_snapshot(self, payload: dict) -> None: ...
        @staticmethod
        def _resolve_periodic_debug_snapshot_dir() -> Path | None: ...
        def _satellite_layer_enabled(self) -> bool: ...
        def _start_persistent_search_refresh(
            self, *, reason: str = "timer"
        ) -> bool: ...
        def request_client_update(self) -> None: ...
        def _clear_cloud_render_buffers(
            self,
            *,
            preserve_cloud_buffers: bool = False,
            preserve_geo_satellite_buffers: bool = False,
        ) -> bool: ...
        def _note_landscape_cursor_motion(self) -> None: ...
        def _request_application_quit(self) -> None: ...
        def _startup_input_blocked(self) -> bool: ...
        def _sync_viewport_interaction_chrome_visibility(self) -> None: ...
        def toggle_simplified_view(self, *, reverse: bool = False) -> None: ...
        def client_height(self) -> int: ...
        def client_width(self) -> int: ...

        # Defined in window_render.py.
        def _viewer_data_for_render(self) -> ViewerData: ...

        # Defined in window_actions.py.
        def _sync_view_altitude_actions(self) -> None: ...
        def toggle_aircraft(self) -> None: ...
        def toggle_asterisms(self) -> None: ...
        def toggle_clouds(self) -> None: ...
        def toggle_dso(self) -> None: ...
        def toggle_earth_guide(self) -> None: ...
        def toggle_fullscreen(self) -> None: ...
        def toggle_guidelines(self) -> None: ...
        def toggle_moon_option(self) -> None: ...
        def toggle_night_lights(self) -> None: ...
        def toggle_sky_disc(self) -> None: ...
        def toggle_terrain_horizon(self) -> None: ...
        def toggle_urban_outline(self) -> None: ...
        def toggle_water_overlay(self) -> None: ...

        # Defined in window_update_overlays.py.
        def reproject_tropical_cyclone_overlay(
            self,
            *,
            allow_during_viewport_interaction: bool = False,
        ) -> None: ...
        def start_background_terrain_horizon_update(
            self, reason: str = "manual"
        ) -> bool: ...
        def start_background_precipitation_update(
            self, reason: str = "manual"
        ) -> bool: ...
        def start_background_urban_outline_update(
            self, reason: str = "manual"
        ) -> bool: ...

        # Defined in window_update_sky.py.
        def request_sky_data_update(
            self,
            star_vmag_limit: float | None = None,
            *,
            reason: str = "manual",
            allow_during_viewport_interaction: bool = False,
        ) -> bool: ...
